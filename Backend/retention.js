export const TERMINOS_RETIRO_VERSION = 'v1';
export const DIAS_RECORDATORIO_RETIRO = [1, 15, 30];

export function proximoRecordatorioRetiro(diasTranscurridos, diasEnviados) {
    return DIAS_RECORDATORIO_RETIRO.find(
        (dia) => dia <= diasTranscurridos && !diasEnviados.has(dia)
    ) ?? null;
}

let esquemaRetiroPromise;

export function asegurarEsquemaRetiro(pool) {
    if (!esquemaRetiroPromise) {
        esquemaRetiroPromise = (async () => {
            await pool.query(`
                ALTER TABLE usuario
                    ADD COLUMN IF NOT EXISTS terminos_retiro_version VARCHAR(20),
                    ADD COLUMN IF NOT EXISTS terminos_retiro_aceptados_en TIMESTAMPTZ
            `);
            await pool.query(`
                ALTER TABLE solicitud
                    ADD COLUMN IF NOT EXISTS fecha_listo_retiro TIMESTAMPTZ
            `);
            await pool.query(`
                UPDATE solicitud
                SET fecha_listo_retiro = CURRENT_TIMESTAMP
                WHERE estado = 'Aprobado' AND fecha_listo_retiro IS NULL
            `);
            await pool.query(`
                CREATE TABLE IF NOT EXISTS notificacion_retiro (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    id_usuario BIGINT NOT NULL,
                    id_solicitud BIGINT NOT NULL,
                    dia INTEGER NOT NULL CHECK (dia IN (1, 15, 30)),
                    titulo TEXT NOT NULL,
                    mensaje TEXT NOT NULL,
                    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    email_enviado_en TIMESTAMPTZ,
                    leida BOOLEAN NOT NULL DEFAULT FALSE,
                    UNIQUE (id_solicitud, dia)
                )
            `);
        })().catch((error) => {
            esquemaRetiroPromise = null;
            throw error;
        });
    }

    return esquemaRetiroPromise;
}
