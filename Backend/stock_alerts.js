export const STOCK_CRITICO_MAXIMO = 2;
export const STOCK_ALERT_NOTIFICATION_ID_OFFSET = 1000000000000;

export function stockEsCritico(stock) {
    if (stock === null || stock === undefined || String(stock).trim() === '') {
        return false;
    }
    const cantidad = Number(stock);
    return Number.isFinite(cantidad) && cantidad <= STOCK_CRITICO_MAXIMO;
}

let esquemaStockPromise;

export function asegurarEsquemaStock(pool) {
    if (!esquemaStockPromise) {
        esquemaStockPromise = (async () => {
            await pool.query(`
                CREATE TABLE IF NOT EXISTS notificacion_stock (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    id_producto BIGINT NOT NULL,
                    id_usuario BIGINT NOT NULL,
                    nombre_producto TEXT NOT NULL,
                    stock INTEGER NOT NULL,
                    activa BOOLEAN NOT NULL DEFAULT TRUE,
                    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    leida BOOLEAN NOT NULL DEFAULT FALSE
                )
            `);
            await pool.query(`
                CREATE UNIQUE INDEX IF NOT EXISTS notificacion_stock_activa_producto_usuario_idx
                ON notificacion_stock (id_producto, id_usuario)
                WHERE activa
            `);
            await pool.query(`
                CREATE INDEX IF NOT EXISTS notificacion_stock_usuario_fecha_idx
                ON notificacion_stock (id_usuario, created_at DESC)
            `);
        })().catch((error) => {
            esquemaStockPromise = null;
            throw error;
        });
    }

    return esquemaStockPromise;
}

export async function sincronizarAlertasStock(pool) {
    await asegurarEsquemaStock(pool);
    const client = await pool.connect();
    try {
        await client.query('BEGIN');
        await client.query('SELECT pg_advisory_xact_lock(84628012)');
        await client.query(
            `UPDATE notificacion_stock alerta
             SET activa = false, leida = true
             WHERE alerta.activa
               AND NOT EXISTS (
                    SELECT 1
                    FROM producto p
                    WHERE p.idproducto = alerta.id_producto
                      AND p.stock <= $1
               )`,
            [STOCK_CRITICO_MAXIMO]
        );
        await client.query(
            `UPDATE notificacion_stock alerta
             SET nombre_producto = p.nombre, stock = p.stock
             FROM producto p
             WHERE alerta.activa
               AND alerta.id_producto = p.idproducto
               AND p.stock <= $1`,
            [STOCK_CRITICO_MAXIMO]
        );
        await client.query(
            `INSERT INTO notificacion_stock
                (id_producto, id_usuario, nombre_producto, stock)
             SELECT p.idproducto, u.idusuario, p.nombre, p.stock
             FROM producto p
             CROSS JOIN usuario u
             JOIN rol r ON r.idrol = u.rol_idrol
             WHERE p.stock <= $1
               AND lower(r.nombrerol) = 'admin'
             ON CONFLICT (id_producto, id_usuario) WHERE activa DO NOTHING`,
            [STOCK_CRITICO_MAXIMO]
        );
        await client.query('COMMIT');
    } catch (error) {
        await client.query('ROLLBACK').catch(() => {});
        throw error;
    } finally {
        client.release();
    }
}
